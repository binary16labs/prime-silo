// Removes a test directory without ever following a reparse point: links, junctions and volume mount
// points are removed as entries (rmdir/unlink), never recursed into.
function safeRemove(dir) {
  let entries;
  try {
    entries = fs.readdirSync(dir, { withFileTypes: true });
  } catch {
    return;
  }
  for (const e of entries) {
    const full = path.join(dir, e.name);
    if (e.isSymbolicLink()) {
      try {
        fs.rmdirSync(full);
      } catch {
        fs.unlinkSync(full);
      }
    } else if (e.isDirectory()) safeRemove(full);
    else fs.unlinkSync(full);
  }
  fs.rmdirSync(dir);
}

// A temporary S0 map, closed before its directory is removed (Windows will not delete an open file).
function tempMap(t) {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), "s1db-"));
  const db = openMap(path.join(dir, "m.db"));
  t.after(() => {
    db.close();
    safeRemove(dir);
  });
  return db;
}

function tempDir(t, prefix) {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), prefix));
  t.after(() => safeRemove(dir));
  return dir;
}

// One real tree, and the CSV that Everything and WizTree would export for it.
function fixtureVolume(t) {
  const vol = tempDir(t, "s1vol-");
  const files = {
    "a.txt": "hello",
    "sub/b.bin": "0123456789",
    "Addams Family, The/game (Beta) [a1].gen": "x".repeat(33),
    "Windows/System32/kernel.dll": "sys",
    "$Recycle.Bin/S-1-5/old.doc": "bin",
    "pagefile.sys": "pf"
  };
  for (const [rel, body] of Object.entries(files)) {
    const full = path.join(vol, ...rel.split("/"));
    fs.mkdirSync(path.dirname(full), { recursive: true });
    fs.writeFileSync(full, body);
  }
  const all = Object.keys(files).map((rel) => {
    const full = path.join(vol, ...rel.split("/"));
    const st = fs.statSync(full, { bigint: true });
    return { full, size: Number(st.size), ns: st.mtimeNs };
  });
  // FILETIME ticks exactly as NTFS stores them (100 ns), so sub-millisecond digits are present
  const everythingCsv =
    "\uFEFF" + all.map((f) => `"${f.full}",32,${f.size},${f.ns / 100n + EPOCH_TICKS}`).join("\r\n");
  const pad = (n) => String(n).padStart(2, "0");
  const wizDate = (d) =>
    `${d.getFullYear()}/${pad(d.getMonth() + 1)}/${pad(d.getDate())} ${pad(d.getHours())}:${pad(d.getMinutes())}:${pad(d.getSeconds())}`;
  const wiztreeCsv = [
    "Generated by WizTree 4.20 (fixture)",
    "File Name,Size,Allocated,Modified,Attributes,Files,Folders",
    `"${vol}\\",100,4096,${wizDate(new Date())},16,6,3`,
    `"${path.join(vol, "sub")}\\",10,4096,${wizDate(new Date())},16,1,0`,
    ...all.map(
      (f) => `"${f.full}",${f.size},4096,${wizDate(new Date(Number(f.ns / 1000000n)))},32,0,0`
    )
  ].join("\r\n");
  return { vol, everythingCsv, wiztreeCsv };
}

// A fake executable runner: writes the fixture to the file the adapter asked for, and records calls.
const fakeExec =
  (csv, { code = 0, count = "6", calls = [] } = {}) =>
  async (cmd, args) => {
    calls.push(args);
    if (args.includes("-get-result-count")) return { code, stdout: count };
    const exportArg = args.indexOf("-export-csv");
    const wizExport = args.find((a) => a.startsWith("/export="));
    const target = exportArg >= 0 ? args[exportArg + 1] : wizExport?.slice("/export=".length);
    if (code === 0 && target) fs.writeFileSync(target, csv);
    return { code, stdout: "" };
  };

const collect = async (adapter, volume) => {
  const rows = [];
  for await (const r of adapter.list(volume)) rows.push(r);
  return rows.sort((a, b) => a.path.localeCompare(b.path));
};

const errno = (code) => Object.assign(new Error(code), { code });
const asLink = (e) => Object.assign(Object.create(e), { isSymbolicLink: () => true });

// A filesystem double over the real fixture: named entries become reparse points, unreadable
// directories, or files whose stat fails; the tag of each reparse directory is given explicitly.
function fsDouble({ reparse = {}, unreadable = [], statFails = {} } = {}) {
  const kindOf = (p) => reparse[path.basename(p)];
  return {
    api: {
      async readdir(dir, opts) {
        if (unreadable.includes(path.basename(dir))) throw errno("EACCES");
        const entries = await fsp.readdir(dir, opts);
        return entries.map((e) => (reparse[e.name] ? asLink(e) : e));
      },
      async readlink(p) {
        if (kindOf(p)?.link) return "C:\\elsewhere";
        throw errno(kindOf(p)?.readlinkError ?? "EINVAL");
      },
      async stat(p, opts) {
        const code = statFails[path.basename(p)];
        if (code) throw errno(code);
        return fsp.stat(p, opts);
      }
    },
    reparseTag: async (p) => kindOf(p)?.tag ?? null
  };
}

test("Scenario: every adapter produces the same rows for the same tree", async (t) => {
  const { vol, everythingCsv, wiztreeCsv } = fixtureVolume(t);
  const calls = [];
  const es = everythingAdapter({ esPath: "es.exe", exec: fakeExec(everythingCsv, { calls }) });
  const wiz = wiztreeAdapter({ wiztreePath: process.execPath, exec: fakeExec(wiztreeCsv) });
  const walked = await collect(walkerAdapter(), vol);
  assert.equal(walked.length, 3, "Windows\\, $Recycle.Bin and pagefile.sys are excluded");
  assert.ok(walked.some((r) => r.path.endsWith("Addams Family, The\\game (Beta) [a1].gen")));
  assert.ok(walked.every((r) => Number.isInteger(r.mtimeMs)));
  // exact: same path spelling, size and millisecond mtime (a BOM on the export is not part of a path)
  assert.deepEqual(await collect(es, vol), walked);
  assert.ok(calls.at(-1).includes(`${vol}\\`), "the volume root is passed with its separator");
  // WizTree's export only has whole local seconds, which is why it is never selected automatically:
  // paths and sizes are exact, mtime only to the second.
  const wizRows = await collect(wiz, vol);
  assert.deepEqual(
    wizRows.map((r) => [r.path, r.size, Math.floor(r.mtimeMs / 1000)]),
    walked.map((r) => [r.path, r.size, Math.floor(r.mtimeMs / 1000)])
  );
});

test("links are excluded and non-link reparse files are listed, identically by every adapter", async (t) => {
  const { vol } = fixtureVolume(t);
  fs.writeFileSync(path.join(vol, "office.dll"), ""); // a link has no data stream: size 0
  fs.writeFileSync(path.join(vol, "dedup.vhdx"), "chunked");
  fs.writeFileSync(path.join(vol, "empty-cloud.txt"), ""); // a size-0 reparse file that is not a link
  fs.writeFileSync(path.join(vol, "empty.txt"), ""); // an ordinary empty file: never a reparse point
  const rows = await collect(walkerAdapter(), vol);
  const reparse = {
    "office.dll": { link: true },
    "dedup.vhdx": { link: false },
    "empty-cloud.txt": { link: false }
  };
  const { api, reparseTag } = fsDouble({ reparse });
  const walked = await collect(walkerAdapter({ fsApi: api, reparseTag }), vol);
  assert.deepEqual(
    walked.map((r) => path.basename(r.path)),
    rows.map((r) => path.basename(r.path)).filter((n) => n !== "office.dll"),
    "walker: the link is dropped, the deduplicated and empty cloud files are listed"
  );

  const line = (name, attrs) => {
    const st = fs.statSync(path.join(vol, name), { bigint: true });
    return `"${path.join(vol, name)}",${attrs},${st.size},${st.mtimeNs / 100n + EPOCH_TICKS}`;
  };
  const names = rows.map((r) => path.relative(vol, r.path));
  const csv = names
    .map((n) => line(n, ["office.dll", "dedup.vhdx", "empty-cloud.txt"].includes(n) ? 1056 : 32))
    .concat(`"${path.join(vol, "vanished.dll")}",1056,0,${EPOCH_TICKS}`)
    .join("\r\n");
  const asked = [];
  const readlink = async (p) => {
    asked.push(path.basename(p));
    if (p.endsWith("office.dll")) return "C:\\target.dll";
    throw errno(p.endsWith("vanished.dll") ? "ENOENT" : "EINVAL");
  };
  const es = everythingAdapter({ esPath: "es.exe", exec: fakeExec(csv), readlink });
  assert.deepEqual(await collect(es, vol), walked, "Everything: same rows as the walker");
  assert.deepEqual(
    asked.sort(),
    ["empty-cloud.txt", "office.dll", "vanished.dll"],
    "only size-0 reparse rows are asked: a file with data (dedup, OneDrive) or without the reparse attribute is never a link"
  );

  const wizCsv = [
    "File Name,Size,Allocated,Modified,Attributes,Files,Folders",
    `"${path.join(vol, "office.dll")}",0,0,2026/09/14 01:00:00,1056,0,0`,
    `"${path.join(vol, "a.txt")}",5,4096,2026/09/14 01:00:00,32,0,0`
  ].join("\r\n");
  const wiz = wiztreeAdapter({ wiztreePath: process.execPath, exec: fakeExec(wizCsv), readlink });
  assert.deepEqual(
    (await collect(wiz, vol)).map((r) => path.basename(r.path)),
    ["a.txt"],
    "WizTree: the link is dropped too"
  );
});

test("an export row this node may not read is a gap, never a file (D16)", async (t) => {
  const { vol } = fixtureVolume(t);
  fs.writeFileSync(path.join(vol, "alias.exe"), ""); // an app execution alias: size 0, reparse, EACCES
  const line = (name, attrs) => {
    const st = fs.statSync(path.join(vol, name), { bigint: true });
    return `"${path.join(vol, name)}",${attrs},${st.size},${st.mtimeNs / 100n + EPOCH_TICKS}`;
  };
  const names = (await collect(walkerAdapter(), vol)).map((r) => path.relative(vol, r.path));
  const csv = names.map((n) => line(n, n === "alias.exe" ? 1056 : 32)).join("\r\n");
  const denied = async (p) => {
    throw errno(p.endsWith("alias.exe") ? "EACCES" : "EINVAL");
  };
  const es = everythingAdapter({ esPath: "es.exe", exec: fakeExec(csv), readlink: denied });
  await assert.rejects(
    collect(es, vol),
    (e) => {
      assert.equal(e.code, "ES_INCOMPLETE");
      assert.deepEqual(e.detail, { unidentifiedReparse: 1 });
      assert.ok(!String(e.message).includes("alias"), "no path in the error");
      return true;
    },
    "Everything refuses the volume, exactly as the walker refuses an entry it cannot stat"
  );

  const wiz = wiztreeAdapter({
    wiztreePath: process.execPath,
    exec: fakeExec(
      [
        "File Name,Size,Allocated,Modified,Attributes,Files,Folders",
        `"${path.join(vol, "alias.exe")}",0,0,2026/09/14 01:00:00,1056,0,0`
      ].join("\r\n")
    ),
    readlink: denied
  });
  await assert.rejects(collect(wiz, vol), { code: "WIZTREE_INCOMPLETE" });

  // S0: the volume is errored with that code, and no row of the refused listing is published
  const db = tempMap(t);
  const sweep = await runSweep({
    db,
    machine: "vm",
    collectors: await fileCollectors([vol], [es]),
    scope: [vol],
    publicRoots: [vol]
  });
  assert.deepEqual(
    [sweep.collectors[0].status, sweep.collectors[0].error_code],
    ["errored", "ES_INCOMPLETE"]
  );
  assert.equal(db.prepare("SELECT COUNT(*) n FROM files").get().n, 0, "no partial rows are kept");
});

