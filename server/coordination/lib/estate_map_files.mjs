// Estate map file collectors (S1) — how a node lists its files, fast, and never silently incompletely.
// Plan: architecture/SOLUTION-estate-map.md §2, §7 · Contract: delivery/tasks/S1.md (amended 2026-09-14) · Model: estate_map.mjs (S0)
//
// Adapters yield the SAME rows ({ path, size, mtimeMs }); S0 records which one ran as the collector name.
// everything: es.exe -export-csv from Everything's live MFT index (1.1M files on t480 F: in ~7 s).
// walker: a plain directory walk that needs nothing installed. Both give exact floored whole-ms mtimes, so
// size+mtime reuse (§2) survives a volume switching adapter. wiztree: WizTree's CSV has whole local seconds,
// so it is benchmarked but never selected automatically. Rules shared by every adapter:
//   - exclusions are applied here, once;
//   - links (anything readlink resolves: symlinks, junctions, app execution aliases) are pointers, not files;
//   - the walker fails with WALK_INCOMPLETE rather than return a partial listing (S0 then keeps the last one).
// Privacy is decided by S0 (names only under public roots): collectors never log or return paths.
import fs from "node:fs";
import fsp from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import readline from "node:readline";
import { spawn } from "node:child_process";

// Operating-system internals nobody manages as files. Matched on the volume-relative path,
// case-insensitively, with either slash.
const EXCLUDED_DIRS = ["windows", "$recycle.bin", "system volume information", "$winreagent"];
const EXCLUDED_ROOT_FILES = ["pagefile.sys", "hiberfil.sys", "swapfile.sys", "dumpstack.log.tmp"];

const slashKey = (s) => String(s).replace(/\\/gu, "/").toLowerCase();

// The volume-relative path (lowercase, forward slashes), or null when the path is not on the volume.
function relativeTo(volume, filePath) {
  const vol = slashKey(volume).replace(/\/+$/u, "");
  const p = slashKey(filePath);
  return p.startsWith(`${vol}/`) ? p.slice(vol.length + 1) : null;
}

export function isExcluded(volume, filePath) {
  const rel = relativeTo(volume, filePath);
  if (rel === null) return false;
  // the excluded folder itself is excluded too, so the walker never descends into it
  if (EXCLUDED_DIRS.includes(rel.split("/")[0])) return true;
  return !rel.includes("/") && EXCLUDED_ROOT_FILES.includes(rel);
}

const volumeRootArg = (volume) => `${String(volume).replace(/[\\/]+$/u, "")}\\`;

// --- parsers (pure) -----------------------------------------------------------------------------

// Floor division for BigInt (plain / truncates toward zero, which is wrong before 1970).
const floorDiv = (a, b) => (a < 0n ? -((-a + b - 1n) / b) : a / b);

// Windows FILETIME (100 ns ticks since 1601) -> whole Unix milliseconds, exact (BigInt).
export function filetimeToMs(ticks) {
  if (!/^\d+$/u.test(ticks)) return null;
  return Number(floorDiv(BigInt(ticks) - 116444736000000000n, 10000n));
}

const REPARSE_POINT = 0x400; // FILE_ATTRIBUTE_REPARSE_POINT

// es.exe -csv with -attributes, -size -size-format 1 (bytes), -date-modified -date-format 2 (FILETIME):
//   "F:\a, b\c.gen",32,1048576,134338232178686205
// Windows file names cannot contain '"', so a quoted first field ends at the last '",' pair.
export function parseEverythingLine(line) {
  const m = /^"(.*)",(\d*),(\d*),(\d*)$/u.exec(line) ?? /^([^",]*),(\d*),(\d*),(\d*)$/u.exec(line);
  if (!m) return null;
  const size = m[3] === "" ? null : Number(m[3]);
  return {
    path: m[1],
    size,
    mtimeMs: filetimeToMs(m[4]),
    reparse: (Number(m[2]) & REPARSE_POINT) !== 0
  };
}

// WizTree CSV export: optional "Generated by WizTree ..." banner, a header row, then
// "File Name",Size,Allocated,Modified,Attributes,Files,Folders. Folder rows end with a backslash.
// The banner and header never match (no numeric size), so only data rows parse.
export function parseWizTreeLine(line) {
  const m = /^"(.*)",(\d*),(\d*),([^,]*),(\d*),/u.exec(line);
  if (!m || /[\\/]$/u.test(m[1])) return null;
  const mtime = Date.parse(m[4].replace(/\//gu, "-").replace(" ", "T"));
  return {
    path: m[1],
    size: m[2] === "" ? null : Number(m[2]),
    mtimeMs: Number.isNaN(mtime) ? null : mtime,
    reparse: (Number(m[5]) & REPARSE_POINT) !== 0
  };
}

// es.exe journal export (header kept):
//   Journal ID,Change ID,Date Changed,Action,Filename,New Filename
// New Filename is a bare name for a rename and a full path for a move; newPath is always the full path.
export function parseJournalCsv(text) {
  const rows = [];
  for (const line of String(text).split(/\r?\n/u)) {
    const m = /^(\d+),(\d+),([^,]*),"([^"]*)","([^"]*)","([^"]*)"$/u.exec(line.trim());
    if (!m) continue;
    const newName = m[6] || null;
    const absolute = newName && /^([a-z]:[\\/]|\\\\)/iu.test(newName);
    const newPath =
      newName && (absolute ? newName : path.win32.join(path.win32.dirname(m[5]), newName));
    rows.push({
      journalId: m[1],
      changeId: Number(m[2]),
      action: m[4],
      path: m[5],
      newName,
      newPath
    });
  }
  return rows;
}

// --- process helpers -------------------------------------------------------------------------

export function defaultEsPath() {
  return (
    process.env.ESTATE_ES ||
    path.join(process.env.LOCALAPPDATA || os.homedir(), "Microsoft", "WinGet", "Links", "es.exe")
  );
}

// Runs a command and resolves { code, stdout }. Never rejects: an absent executable is code -1,
// and a command still running at the timeout is killed and resolves code -1.
export function run(cmd, args, { timeoutMs = 600_000 } = {}) {
  return new Promise((resolve) => {
    let stdout = "";
    const done = (code) => {
      clearTimeout(timer);
      resolve({ code, stdout });
    };
    const child = spawn(cmd, args, { windowsHide: true });
    const timer = setTimeout(() => {
      child.kill();
      done(-1);
    }, timeoutMs);
    child.stdout?.on("data", (d) => (stdout += d));
    child.on("error", () => done(-1));
    child.on("close", (code) => done(code ?? -1));
  });
}

const failure = (code, detail) =>
  Object.assign(new Error("file adapter failed"), { code }, detail ? { detail } : {});

// A reparse file is a link when readlink resolves it. One that vanished since the export is dropped;
// one readlink cannot judge (not a link, or unreadable) is kept, as the index lists it.
async function isLink(file, readlink) {
  try {
    await readlink(file);
    return true;
  } catch (e) {
    return e?.code === "ENOENT";
  }
}

async function* readLines(file, parse, volume, readlink) {
  const input = fs.createReadStream(file, { encoding: "utf8" });
  for await (const line of readline.createInterface({ input, crlfDelay: Infinity })) {
    const row = parse(line.replace(/^\uFEFF/u, ""));
    if (!row || isExcluded(volume, row.path)) continue;
    // a link (symlink, junction, app execution alias) has no data stream, so its size is 0; only those
    // rows are asked (8,420 of 1.0M reparse rows on t480 C:, which are mostly OneDrive cloud files)
    if (row.reparse && row.size === 0 && (await isLink(row.path, readlink))) continue;
    yield { path: row.path, size: row.size, mtimeMs: row.mtimeMs };
  }
}

async function withTempFile(tag, use) {
  const dir = await fsp.mkdtemp(path.join(os.tmpdir(), `estate-map-${tag}-`));
  try {
    return await use(path.join(dir, "export.csv"));
  } finally {
    await fsp.rm(dir, { recursive: true, force: true });
  }
}

// --- adapters ------------------------------------------------------------------------------------

const ES_LIST = ["file:", "-attributes", "-size", "-date-modified", "-size-format", "1"];
const JOURNAL_TIMEOUT_MS = 60_000;

const validPosition = (p) =>
  /^\d+$/u.test(String(p?.journalId)) && Number.isSafeInteger(p?.changeId) && p.changeId >= 0;

export function everythingAdapter({
  esPath = defaultEsPath(),
  exec = run,
  readlink = fsp.readlink
} = {}) {
  const position = async () => {
    const r = await exec(esPath, ["-get-journal-pos"]);
    const m = /^(\d+)\s+(\d+)/u.exec(r.stdout.trim());
    return r.code === 0 && m ? { journalId: m[1], changeId: Number(m[2]) } : null;
  };
  return {
    name: "everything",
    async available(volume) {
      const r = await exec(esPath, ["-get-result-count", "-path", volumeRootArg(volume), "file:"]);
      return r.code === 0 && Number(r.stdout.trim()) > 0;
    },
    async *list(volume) {
      const dir = await fsp.mkdtemp(path.join(os.tmpdir(), "estate-map-es-"));
      try {
        const file = path.join(dir, "export.csv");
        const tail = ["-date-format", "2", "-export-csv", file, "-no-header"];
        const r = await exec(esPath, ["-path", volumeRootArg(volume), ...ES_LIST, ...tail]);
        if (r.code !== 0) throw failure(r.code === 8 ? "ES_UNAVAILABLE" : "ES_FAILED");
        yield* readLines(file, parseEverythingLine, volume, readlink);
      } finally {
        await fsp.rm(dir, { recursive: true, force: true });
      }
    },
    journalPosition: position,
    // Changes in [from, now) touching this volume (from it, or moved into it) + the resume position. es
    // hangs on an open-ended range or a start older than it retains (~30 min on t480), ignores -path here
    // and pipes the console code page, so fetch the retained journal [0, now) as UTF-8 and decide here.
    // Malformed position: ES_JOURNAL_POSITION_INVALID; lost changes: ES_JOURNAL_GAP; Everything
    // re-indexed: ES_JOURNAL_RESET. Each means the volume must be listed again.
    async changesSince(from, volume) {
      if (!validPosition(from)) throw failure("ES_JOURNAL_POSITION_INVALID");
      const to = await position();
      if (!to) throw failure("ES_JOURNAL_UNAVAILABLE");
      if (String(from.journalId) !== to.journalId) throw failure("ES_JOURNAL_RESET");
      const all = await withTempFile("journal", async (file) => {
        const range = ["-from-journal-pos", to.journalId, "0", "-to-journal-pos", to.journalId];
        const args = [...range, String(to.changeId), "-export-csv", file];
        const r = await exec(esPath, args, { timeoutMs: JOURNAL_TIMEOUT_MS });
        if (r.code !== 0 || !fs.existsSync(file)) throw failure("ES_JOURNAL_UNAVAILABLE");
        return parseJournalCsv(await fsp.readFile(file, "utf8"));
      });
      let oldest = to.changeId;
      for (const c of all) if (c.changeId < oldest) oldest = c.changeId;
      if (from.changeId < oldest || from.changeId > to.changeId) throw failure("ES_JOURNAL_GAP");
      const touches = (p) => p && relativeTo(volume, p) !== null && !isExcluded(volume, p);
      const changes = all.filter(
        (c) => c.changeId >= from.changeId && (touches(c.path) || touches(c.newPath))
      );
      return { changes, position: to };
    }
  };
}

export function wiztreeAdapter({
  wiztreePath = process.env.ESTATE_WIZTREE || "C:\\Program Files\\WizTree\\WizTree64.exe",
  exec = run,
  readlink = fsp.readlink
} = {}) {
  return {
    name: "wiztree",
    async available() {
      return fs.existsSync(wiztreePath);
    },
    async *list(volume) {
      const dir = await fsp.mkdtemp(path.join(os.tmpdir(), "estate-map-wiztree-"));
      try {
        const file = path.join(dir, "export.csv");
        const flags = ["/admin=0", "/exportfiles=1", "/exportfolders=0"];
        const r = await exec(wiztreePath, [volumeRootArg(volume), `/export=${file}`, ...flags]);
        if (r.code !== 0 || !fs.existsSync(file)) throw failure("WIZTREE_FAILED");
        yield* readLines(file, parseWizTreeLine, volume, readlink);
      } finally {
        await fsp.rm(dir, { recursive: true, force: true });
      }
    }
  };
}

// The reparse tag of a path (fsutil needs no elevation and works on UNC paths), or null.
export async function fsutilReparseTag(p) {
  const r = await run("fsutil", ["reparsepoint", "query", p], { timeoutMs: 30_000 });
  const m = /Reparse Tag Value\s*:\s*0x([0-9a-f]+)/iu.exec(r.stdout);
  return r.code === 0 && m ? Number.parseInt(m[1], 16) : null;
}

// IO_REPARSE_TAG_CLOUD and its 16 variants (0x9000001A, 0x9000101A ... 0x9000F01A): OneDrive folders.
export const isCloudTag = (tag) => tag !== null && (tag & 0xffff0fff) >>> 0 === 0x9000001a;
const MOUNT_POINT_TAG = 0xa0000003; // a junction whose target readlink cannot resolve: a volume

// Node reports every reparse point as a symlink. A link (readlink resolves it) is never followed or
// listed. Of the rest, a file is listed; a directory is walked only when its tag says cloud folder, is
// skipped when it is a volume mount point (another volume, or a loop back to this one, on any path form),
// and otherwise cannot be judged and counts as skipped. Any skip — unreadable directory, a file that
// cannot be stat'ed, an unidentified reparse directory — ends the walk with WALK_INCOMPLETE and counts.
export function walkerAdapter({ fsApi = fsp, reparseTag = fsutilReparseTag } = {}) {
  return {
    name: "walker",
    async available() {
      return true;
    },
    async *list(volume) {
      const skipped = { directories: 0, files: 0, reparse: 0 };
      const gone = (e) => e?.code === "ENOENT"; // deleted while walking: churn, not a gap
      const stack = [volumeRootArg(volume)];
      while (stack.length) {
        const dir = stack.pop();
        let entries;
        try {
          entries = await fsApi.readdir(dir, { withFileTypes: true });
        } catch (e) {
          if (!gone(e) || dir === volumeRootArg(volume)) skipped.directories++;
          continue;
        }
        for (const e of entries) {
          const full = path.join(dir, e.name);
          if (isExcluded(volume, full)) continue;
          const reparse = e.isSymbolicLink();
          if (reparse && (await isLink(full, fsApi.readlink))) continue;
          let st;
          try {
            st = await fsApi.stat(full, { bigint: true });
          } catch (err) {
            if (!gone(err)) skipped.files++;
            continue;
          }
          if (st.isDirectory()) {
            const tag = reparse ? await reparseTag(full) : null;
            if (!reparse || isCloudTag(tag)) stack.push(full);
            else if (tag !== MOUNT_POINT_TAG) skipped.reparse++;
          } else if (st.isFile())
            yield {
              path: full,
              size: Number(st.size),
              mtimeMs: Number(floorDiv(st.mtimeNs, 1000000n))
            };
        }
      }
      if (skipped.directories + skipped.files + skipped.reparse > 0)
        throw failure("WALK_INCOMPLETE", skipped);
    }
  };
}

// --- selection: one S0 collector per adapter, named for it, holding the volumes it serves ---------

function collectorsFor(pairs) {
  const byAdapter = new Map();
  for (const [volume, adapter] of pairs) {
    if (!byAdapter.has(adapter)) byAdapter.set(adapter, []);
    byAdapter.get(adapter).push(volume);
  }
  return [...byAdapter].map(([adapter, vols]) => ({
    name: `files-${adapter.name}`,
    kind: "files",
    volumes: vols,
    collect: ({ volume }) => adapter.list(volume)
  }));
}

export async function selectAdapters(volumes, adapters) {
  const chosen = new Map();
  for (const volume of volumes)
    for (const a of adapters)
      if (await Promise.resolve(a.available(volume)).catch(() => false)) {
        chosen.set(volume, a);
        break;
      }
  return chosen;
}

// Default selection: Everything, else the walker (WizTree is benchmark-only; see the header).
export async function fileCollectors(volumes, adapters = [everythingAdapter(), walkerAdapter()]) {
  return collectorsFor(await selectAdapters(volumes, adapters));
}

// The benchmark's own decision, turned into collectors: each volume uses the adapter it chose.
export function decidedCollectors(decision, adapters) {
  return collectorsFor(
    decision
      .map((d) => [d.volume, adapters.find((a) => a.name === d.chosen)])
      .filter(([, adapter]) => adapter)
  );
}

// --- the benchmark's decision (pure): the fastest adapter that finished, never a slower one ---

export function recommend(results) {
  const byVolume = new Map();
  for (const r of results) {
    if (!byVolume.has(r.volume)) byVolume.set(r.volume, []);
    byVolume.get(r.volume).push(r);
  }
  return [...byVolume].map(([volume, rs]) => {
    const finished = rs.filter((r) => r.ok).sort((a, b) => a.seconds - b.seconds);
    const walker = rs.find((r) => r.adapter === "walker" && r.ok);
    const best = finished[0] ?? null;
    return {
      volume,
      chosen: best?.adapter ?? null,
      seconds: best?.seconds ?? null,
      walkerSeconds: walker?.seconds ?? null,
      speedupOverWalker:
        best && walker ? +(walker.seconds / Math.max(best.seconds, 0.01)).toFixed(1) : null,
      all: rs.map((r) => ({ ...r }))
    };
  });
}
