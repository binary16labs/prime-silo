// Estate map file collectors (S1) — how a node lists its files, fast.
// Plan: architecture/SOLUTION-estate-map.md §2, §7 · Contract: delivery/tasks/S1.md · Model: estate_map.mjs (S0)
//
// Three adapters produce the SAME rows ({ path, size, mtimeMs }) for a volume, so S0 cannot tell
// which one ran except by the collector name it records on the volume row:
//
//   everything — Everything (voidtools) already holds an MFT/USN-journal index. `es.exe -export-csv`
//                writes a whole volume listing to disk in seconds (1.1M files on t480 F: in ~4 s).
//   wiztree    — WizTree reads the MFT and exports a CSV snapshot (no live index).
//   walker     — a plain directory walk. Slow, but works on any filesystem and needs nothing installed.
//
// Which adapter a volume uses is decided per volume by what is actually available, and the
// benchmark (scripts/estate_map_bench.mjs) reports every adapter's time on the same volumes so the
// choice is measured, not assumed. Exclusions are applied here, once, identically for all three.
//
// Privacy is NOT decided here: every row goes to S0's runSweep, which lists names only under public
// roots. Collectors must therefore never log or return paths themselves.
import fs from "node:fs";
import fsp from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import readline from "node:readline";
import { spawn } from "node:child_process";

// Operating-system internals nobody manages as files. Matched on the volume-relative path,
// case-insensitively, with either slash.
const EXCLUDED_DIRS = ["windows", "$recycle.bin", "system volume information", "$winreagent"];
const EXCLUDED_ROOT_FILES = ["pagefile.sys", "hiberfil.sys", "swapfile.sys", "dumpstack.log.tmp"];

export function isExcluded(volume, filePath) {
  const vol = String(volume).replace(/\\/gu, "/").replace(/\/+$/u, "").toLowerCase();
  const p = String(filePath).replace(/\\/gu, "/").toLowerCase();
  if (!p.startsWith(`${vol}/`)) return false;
  const rel = p.slice(vol.length + 1);
  // the excluded folder itself is excluded too, so the walker never descends into it
  if (EXCLUDED_DIRS.includes(rel.split("/")[0])) return true;
  return !rel.includes("/") && EXCLUDED_ROOT_FILES.includes(rel);
}

const volumeRootArg = (volume) => `${String(volume).replace(/[\\/]+$/u, "")}\\`;

// --- parsers (pure) -----------------------------------------------------------------------------

// es.exe -csv with -size-format 1 (bytes) -date-format 3 (ISO-8601 UTC):
//   "F:\a, b\c.gen",1048576,2000-10-29T04:00:00Z
// Windows file names cannot contain '"', so a quoted first field ends at the last '",' pair.
export function parseEverythingLine(line) {
  const m = /^"(.*)",(\d*),(.*)$/u.exec(line) ?? /^([^",]*),(\d*),(.*)$/u.exec(line);
  if (!m) return null;
  const mtime = Date.parse(m[3]);
  return {
    path: m[1],
    size: m[2] === "" ? null : Number(m[2]),
    mtimeMs: Number.isNaN(mtime) ? null : mtime
  };
}

// WizTree CSV export: optional "Generated by WizTree ..." banner, a header row, then
// "File Name",Size,Allocated,Modified,Attributes,Files,Folders. Folder rows end with a backslash.
// The banner and header never match (no numeric size), so only data rows parse.
export function parseWizTreeLine(line) {
  const m = /^"(.*)",(\d*),(\d*),([^,]*),/u.exec(line);
  if (!m || /[\\/]$/u.test(m[1])) return null;
  const mtime = Date.parse(m[4].replace(/\//gu, "-").replace(" ", "T"));
  return {
    path: m[1],
    size: m[2] === "" ? null : Number(m[2]),
    mtimeMs: Number.isNaN(mtime) ? null : mtime
  };
}

// es.exe -after-journal-pos ... -csv (header kept):
//   Journal ID,Change ID,Date Changed,Action,Filename,New Filename
export function parseJournalCsv(text) {
  const rows = [];
  for (const line of String(text).split(/\r?\n/u)) {
    const m = /^(\d+),(\d+),([^,]*),"([^"]*)","([^"]*)","([^"]*)"$/u.exec(line.trim());
    if (m)
      rows.push({
        journalId: m[1],
        changeId: Number(m[2]),
        action: m[4],
        path: m[5],
        newName: m[6] || null
      });
  }
  return rows;
}

// --- process helpers -------------------------------------------------------------------------

export function defaultEsPath() {
  return (
    process.env.ESTATE_ES ||
    path.join(process.env.LOCALAPPDATA || os.homedir(), "Microsoft", "WinGet", "Links", "es.exe")
  );
}

// Runs a command and resolves { code, stdout }. Never rejects: an absent executable is code -1.
export function run(cmd, args, { timeoutMs = 600_000 } = {}) {
  return new Promise((resolve) => {
    let stdout = "";
    let child;
    try {
      child = spawn(cmd, args, { windowsHide: true });
    } catch {
      return resolve({ code: -1, stdout: "" });
    }
    const timer = setTimeout(() => child.kill(), timeoutMs);
    child.stdout?.on("data", (d) => (stdout += d));
    child.on("error", () => {
      clearTimeout(timer);
      resolve({ code: -1, stdout });
    });
    child.on("close", (code) => {
      clearTimeout(timer);
      resolve({ code: code ?? -1, stdout });
    });
  });
}

const failure = (code) => Object.assign(new Error("file adapter failed"), { code });

async function* readLines(file, parse, volume) {
  const rl = readline.createInterface({
    input: fs.createReadStream(file, { encoding: "utf8" }),
    crlfDelay: Infinity
  });
  for await (const line of rl) {
    const row = parse(line.replace(/^\uFEFF/u, ""));
    if (row && !isExcluded(volume, row.path)) yield row;
  }
}

async function tempFile(tag) {
  const dir = await fsp.mkdtemp(path.join(os.tmpdir(), `estate-map-${tag}-`));
  return {
    file: path.join(dir, "export.csv"),
    cleanup: () => fsp.rm(dir, { recursive: true, force: true })
  };
}

// --- adapters ------------------------------------------------------------------------------------

export function everythingAdapter({ esPath = defaultEsPath(), exec = run } = {}) {
  return {
    name: "everything",
    async available(volume) {
      const r = await exec(esPath, ["-get-result-count", `path:${volumeRootArg(volume)}`, "file:"]);
      return r.code === 0 && Number(r.stdout.trim()) > 0;
    },
    async *list(volume) {
      const t = await tempFile("es");
      try {
        const args = [
          "-path",
          volumeRootArg(volume),
          "file:",
          "-size",
          "-date-modified",
          "-size-format",
          "1",
          "-date-format",
          "3",
          "-export-csv",
          t.file,
          "-no-header"
        ];
        const r = await exec(esPath, args);
        if (r.code !== 0) throw failure(r.code === 8 ? "ES_UNAVAILABLE" : "ES_FAILED");
        yield* readLines(t.file, parseEverythingLine, volume);
      } finally {
        await t.cleanup();
      }
    },
    async journalPosition() {
      const r = await exec(esPath, ["-get-journal-pos"]);
      const m = /^(\d+)\s+(\d+)/u.exec(r.stdout.trim());
      return r.code === 0 && m ? { journalId: m[1], changeId: Number(m[2]) } : null;
    },
    async changesSince({ journalId, changeId }, volume) {
      const r = await exec(esPath, [
        "-after-journal-pos",
        journalId,
        String(changeId),
        "-path",
        volumeRootArg(volume),
        "-csv"
      ]);
      if (r.code !== 0) throw failure("ES_JOURNAL_UNAVAILABLE");
      return parseJournalCsv(r.stdout).filter((c) => !isExcluded(volume, c.path));
    }
  };
}

export function wiztreeAdapter({
  wiztreePath = process.env.ESTATE_WIZTREE || "C:\\Program Files\\WizTree\\WizTree64.exe",
  exec = run
} = {}) {
  return {
    name: "wiztree",
    async available() {
      return fs.existsSync(wiztreePath);
    },
    async *list(volume) {
      const t = await tempFile("wiztree");
      try {
        const r = await exec(wiztreePath, [
          volumeRootArg(volume),
          `/export=${t.file}`,
          "/admin=0",
          "/exportfiles=1",
          "/exportfolders=0"
        ]);
        if (r.code !== 0 || !fs.existsSync(t.file)) throw failure("WIZTREE_FAILED");
        yield* readLines(t.file, parseWizTreeLine, volume);
      } finally {
        await t.cleanup();
      }
    }
  };
}

export function walkerAdapter() {
  return {
    name: "walker",
    async available() {
      return true;
    },
    async *list(volume) {
      const root = volumeRootArg(volume);
      const stack = [root];
      while (stack.length) {
        const dir = stack.pop();
        let entries;
        try {
          entries = await fsp.readdir(dir, { withFileTypes: true });
        } catch {
          continue; // unreadable directory: skipped, like the MFT tools skip what they cannot open
        }
        for (const e of entries) {
          const full = path.join(dir, e.name);
          if (isExcluded(volume, full)) continue;
          if (e.isSymbolicLink()) continue; // junctions and links would revisit or loop
          if (e.isDirectory()) stack.push(full);
          else if (e.isFile()) {
            try {
              const st = await fsp.stat(full);
              yield { path: full, size: st.size, mtimeMs: Math.floor(st.mtimeMs) };
            } catch {
              // vanished or locked between readdir and stat
            }
          }
        }
      }
    }
  };
}

// --- selection: one S0 collector per adapter, named for it, holding the volumes it serves ---------

export async function selectAdapters(volumes, adapters) {
  const chosen = new Map();
  for (const volume of volumes) {
    let pick = null;
    for (const a of adapters) {
      let ok = false;
      try {
        ok = await a.available(volume);
      } catch {
        ok = false;
      }
      if (ok) {
        pick = a;
        break;
      }
    }
    if (pick) chosen.set(volume, pick);
  }
  return chosen;
}

export async function fileCollectors(
  volumes,
  adapters = [everythingAdapter(), wiztreeAdapter(), walkerAdapter()]
) {
  const chosen = await selectAdapters(volumes, adapters);
  const byAdapter = new Map();
  for (const [volume, adapter] of chosen) {
    if (!byAdapter.has(adapter)) byAdapter.set(adapter, []);
    byAdapter.get(adapter).push(volume);
  }
  return [...byAdapter].map(([adapter, vols]) => ({
    name: `files-${adapter.name}`,
    kind: "files",
    volumes: vols,
    collect: ({ volume }) => adapter.list(volume)
  }));
}

// --- the benchmark's decision (pure): the fastest adapter that finished, never a slower one ---

export function recommend(results) {
  const byVolume = new Map();
  for (const r of results) {
    if (!byVolume.has(r.volume)) byVolume.set(r.volume, []);
    byVolume.get(r.volume).push(r);
  }
  return [...byVolume].map(([volume, rs]) => {
    const finished = rs.filter((r) => r.ok).sort((a, b) => a.seconds - b.seconds);
    const walker = rs.find((r) => r.adapter === "walker" && r.ok);
    const best = finished[0] ?? null;
    return {
      volume,
      chosen: best?.adapter ?? null,
      seconds: best?.seconds ?? null,
      walkerSeconds: walker?.seconds ?? null,
      speedupOverWalker: best && walker ? +(walker.seconds / best.seconds).toFixed(1) : null,
      all: rs.map(({ adapter, ok, seconds, files, errorCode }) => ({
        adapter,
        ok,
        seconds,
        files,
        errorCode
      }))
    };
  });
}
